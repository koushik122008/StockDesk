import nodemailer from "nodemailer";
import { prisma } from "@/lib/prisma";

export interface StockChangeContext {
  productId: string;
  previousQuantity: number;
  newQuantity: number;
}

/**
 * Check product stock level against reorder threshold.
 * Exactly one alert generated when stock drops below threshold.
 * Re-armed when stock is restored above reorder level.
 */
export async function evaluateStockAlerts(ctx: StockChangeContext) {
  const { productId, previousQuantity, newQuantity } = ctx;

  const product = await prisma.product.findUnique({
    where: { id: productId },
    include: {
      category: true,
      retailers: {
        where: { isPrimary: true },
        include: { retailer: true },
      },
    },
  });

  if (!product) return;

  const reorderThreshold = product.minReorderLevel ?? product.category.defaultReorderLevel ?? 5;
  const primaryRetailer = product.retailers[0]?.retailer;

  // Case 1: Item crosses below or equal to reorder level and alert is armed
  if (newQuantity <= reorderThreshold && product.alertArmed) {
    const isOutOfStock = newQuantity === 0;
    const alertType = isOutOfStock ? "OUT_OF_STOCK" : "LOW_STOCK";
    const title = isOutOfStock
      ? `Out of Stock: ${product.name}`
      : `Low Stock Alert: ${product.name}`;

    const retailerInfo = primaryRetailer
      ? `Supplier: ${primaryRetailer.name} (${primaryRetailer.phone})`
      : "Supplier: Unassigned";

    const message = `${product.name} (SKU: ${product.sku}) has ${
      isOutOfStock ? "run out" : `only ${newQuantity} unit(s) remaining`
    } (Reorder level: ${reorderThreshold}). ${retailerInfo}.`;

    // 1. Create in-app notification
    await prisma.notification.create({
      data: {
        type: alertType,
        title,
        message,
        productId: product.id,
        isRead: false,
      },
    });

    // 2. Disarm alert on product so duplicate drops don't re-trigger
    await prisma.product.update({
      where: { id: product.id },
      data: { alertArmed: false },
    });

    // 3. Dispatch Email Alert
    await dispatchEmailAlert({
      subject: `[StockDesk Alert] ${title}`,
      productName: product.name,
      sku: product.sku,
      currentQty: newQuantity,
      reorderLevel: reorderThreshold,
      retailer: primaryRetailer,
    });

    // 4. Dispatch Webhook (Telegram / WhatsApp) if configured
    await dispatchWebhookAlert({
      title,
      message,
      productName: product.name,
      sku: product.sku,
      currentQty: newQuantity,
      reorderLevel: reorderThreshold,
    });
  }

  // Case 2: Stock restocked above reorder level -> Re-arm alert
  else if (newQuantity > reorderThreshold && !product.alertArmed) {
    await prisma.product.update({
      where: { id: product.id },
      data: { alertArmed: true },
    });
  }
}

/**
 * Send email alert using Nodemailer.
 * In development or mock SMTP, logs to console and handles test accounts gracefully.
 */
async function dispatchEmailAlert(info: {
  subject: string;
  productName: string;
  sku: string;
  currentQty: number;
  reorderLevel: number;
  retailer?: any;
}) {
  const host = process.env.SMTP_HOST || "localhost";
  const port = parseInt(process.env.SMTP_PORT || "587");
  const user = process.env.SMTP_USER;
  const pass = process.env.SMTP_PASS;
  const from = process.env.SMTP_FROM || "StockDesk Alerts <alerts@stockdesk.local>";
  const to = process.env.OWNER_EMAIL || "owner@stockdesk.local";

  const emailBody = `
========================================
STOCKDESK INVENTORY ALERT
========================================

Item: ${info.productName}
SKU: ${info.sku}
Current Quantity: ${info.currentQty} unit(s)
Reorder Threshold: ${info.reorderLevel} unit(s)

${
  info.retailer
    ? `Recommended Distributor:
Name: ${info.retailer.name}
Contact: ${info.retailer.contactPerson} (${info.retailer.phone})
Email: ${info.retailer.email}
GSTIN: ${info.retailer.gstin}`
    : "No primary retailer assigned."
}

Please reorder promptly to prevent stock-outs.
Generated by StockDesk Host Server
  `;

  try {
    const transporter = nodemailer.createTransport({
      host,
      port,
      secure: port === 465,
      auth: user ? { user, pass } : undefined,
      tls: { rejectUnauthorized: false },
    });

    await transporter.sendMail({
      from,
      to,
      subject: info.subject,
      text: emailBody,
    });
    console.log(`✉️ Low-stock email alert sent to ${to} for ${info.sku}`);
  } catch (err: any) {
    // If SMTP server is not a real internet host, log formatted alert to terminal
    console.log(`[SMTP Dispatch Notice] (Offline/Dev): Email alert generated for ${info.sku} -> ${to}`);
  }
}

/**
 * Dispatch webhook to external URL if configured
 */
async function dispatchWebhookAlert(payload: any) {
  const webhookUrl = process.env.NOTIFICATION_WEBHOOK_URL;
  if (!webhookUrl) return;

  try {
    await fetch(webhookUrl, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
  } catch (err) {
    console.warn("Webhook dispatch failed:", err);
  }
}
